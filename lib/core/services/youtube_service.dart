/// YouTube source resolution for the video tab.
///
/// Port of jidoujisho's youtube.dart, trimmed to what this app's player
/// needs: resolve a pasted URL to metadata and the muxed stream list, and
/// fetch closed captions as subtitle cues. Muxed streams only — playing
/// video-only streams needs separate audio muxing, which video_player
/// (unlike jidoujisho's desktop VLC player) does not offer.
library;

import 'package:lang/utils/subtitle_parser.dart';
import 'package:youtube_explode_dart/youtube_explode_dart.dart';

/// What a YouTube source backend offers. yt-dlp and youtube_explode both
/// implement this; the resolver picks whichever can serve the request.
abstract interface class YouTubeBackend {
  Future<YouTubeVideoInfo?> resolve(String url);

  Future<List<YouTubeCaptionTrack>> captionTracks(String videoId);

  Future<List<SubtitleCue>> fetchCaptions(YouTubeCaptionTrack track);
}

/// One playable quality from the manifest.
class YouTubeStreamOption {
  const YouTubeStreamOption({required this.url, required this.label});

  /// Direct media URL for the stream. Expires after a few hours, so the
  /// list is only good for one playback session.
  final String url;

  /// Resolution label shown in the picker, e.g. `360p`.
  final String label;
}

/// Metadata and qualities for a resolved YouTube video.
class YouTubeVideoInfo {
  const YouTubeVideoInfo({
    required this.videoId,
    required this.title,
    required this.author,
    required this.qualities,
  });

  final String videoId;
  final String title;
  final String author;

  /// Sorted smallest to largest; the last entry is the best quality.
  final List<YouTubeStreamOption> qualities;

  /// The default stream to play: the highest quality available.
  YouTubeStreamOption get best => qualities.last;

  /// What the player shows for this video: `title · author`, falling back
  /// to the video ID when the watch-page scrape was blocked.
  String get displayLabel =>
      title.isEmpty ? videoId : (author.isEmpty ? title : '$title · $author');
}

/// One closed-caption track: language plus where to fetch it.
class YouTubeCaptionTrack {
  const YouTubeCaptionTrack({
    required this.videoId,
    required this.languageCode,
    required this.languageName,
    required this.autoGenerated,
    this.url,
  });

  /// The video the track belongs to; caption URLs expire after a few
  /// hours, so fetching resolves the manifest fresh by video ID.
  final String videoId;

  /// Direct caption URL in a format the local parsers understand, when
  /// the backend already extracted one (yt-dlp). Null for explode
  /// tracks, which resolve the manifest fresh at fetch time.
  final String? url;

  final String languageCode;
  final String languageName;
  final bool autoGenerated;

  /// The label the picker shows, e.g. `Japanese (auto-generated)`.
  String get label => autoGenerated
      ? '$languageName (auto-generated)'
      : (languageName.isEmpty ? languageCode : languageName);
}

/// Resolves YouTube videos and captions for the player tab.
class YouTubeService implements YouTubeBackend {
  const YouTubeService();

  /// Normalize resolution labels and dedupe to one stream per label, the
  /// way jidoujisho's quality menu did: `720` becomes `720p`, `720p60`
  /// collapses into `720p`. Returned smallest to largest so the picker
  /// reads naturally and the last entry is the best quality.
  static List<YouTubeStreamOption> qualityOptions(
    Iterable<({String url, String qualityLabel})> streams,
  ) {
    final byLabel = <String, YouTubeStreamOption>{};
    for (final stream in streams) {
      var label = stream.qualityLabel;
      if (!label.contains('p')) label = '${label}p';
      label = label.replaceAll('p60', 'p');
      byLabel.putIfAbsent(
        label,
        () => YouTubeStreamOption(url: stream.url, label: label),
      );
    }
    final options = byLabel.values.toList()
      ..sort((a, b) => _height(a.label).compareTo(_height(b.label)));
    return options;
  }

  /// The numeric part of a resolution label (`720p` → 720).
  static int _height(String label) =>
      int.tryParse(label.replaceAll(RegExp(r'\D'), '')) ?? 0;

  /// Extract the 11-character video ID from any YouTube URL form
  /// (watch?v=, youtu.be/, shorts/, embed/, or a bare ID). Returns null for
  /// garbage input so callers can show their own error.
  String? parseVideoId(String urlOrId) {
    try {
      return VideoId(urlOrId).value;
    } on Object {
      return null;
    }
  }

  /// Resolve a URL or ID to metadata and the muxed quality list. Returns
  /// null when the input is not a video or no muxed streams are available.
  ///
  /// The stream manifest skips the watch page ([StreamClient.getManifest]
  /// fetches it by default, and YouTube rate-limits watch-page hits far
  /// more aggressively than the innertube API). Video metadata is scraped
  /// from the watch page and is cosmetic, so a blocked scrape degrades to
  /// an empty title instead of killing playback.
  @override
  Future<YouTubeVideoInfo?> resolve(String urlOrId) async {
    final id = parseVideoId(urlOrId);
    if (id == null) return null;

    final yt = YoutubeExplode();
    try {
      String title;
      String author;
      try {
        final video = await yt.videos.get(id);
        title = video.title;
        author = video.author;
      } on Object {
        title = '';
        author = '';
      }
      final manifest = await yt.videos.streams.getManifest(
        id,
        requireWatchPage: false,
      );
      final qualities = qualityOptions([
        for (final s in manifest.muxed)
          (url: s.url.toString(), qualityLabel: s.qualityLabel),
      ]);
      if (qualities.isEmpty) return null;
      return YouTubeVideoInfo(
        videoId: id,
        title: title,
        author: author,
        qualities: qualities,
      );
    } finally {
      yt.close();
    }
  }

  /// Closed-caption tracks for a video, manual tracks first then
  /// alphabetically by language code. The manifest lists several format
  /// variants per language; they all point at the same content, so
  /// collapse them into one track per language.
  @override
  Future<List<YouTubeCaptionTrack>> captionTracks(String videoId) async {
    final yt = YoutubeExplode();
    try {
      final manifest = await yt.videos.closedCaptions.getManifest(videoId);
      final sorted = manifest.tracks.toList()
        ..sort((a, b) {
          final byAuto = (a.isAutoGenerated ? 1 : 0).compareTo(
            b.isAutoGenerated ? 1 : 0,
          );
          if (byAuto != 0) return byAuto;
          return a.language.code.compareTo(b.language.code);
        });
      final seen = <String>{};
      final tracks = <YouTubeCaptionTrack>[];
      for (final track in sorted) {
        if (!seen.add(track.language.code)) continue;
        tracks.add(
          YouTubeCaptionTrack(
            videoId: videoId,
            languageCode: track.language.code,
            languageName: track.language.name,
            autoGenerated: track.isAutoGenerated,
          ),
        );
      }
      return tracks;
    } finally {
      yt.close();
    }
  }

  /// Fetch one caption track as subtitle cues for the transcript and the
  /// overlay. The manifest is resolved again here because caption URLs
  /// expire after a few hours; the track with the matching language is
  /// used with its original info, which the caption client needs.
  @override
  Future<List<SubtitleCue>> fetchCaptions(YouTubeCaptionTrack track) async {
    final yt = YoutubeExplode();
    try {
      final manifest = await yt.videos.closedCaptions.getManifest(
        track.videoId,
      );
      final info = manifest.tracks.firstWhere(
        (t) =>
            t.language.code == track.languageCode &&
            t.isAutoGenerated == track.autoGenerated,
        orElse: () => manifest.tracks.firstWhere(
          (t) => t.language.code == track.languageCode,
        ),
      );
      final captions = await yt.videos.closedCaptions.get(info);
      final cues = [
        for (final caption in captions.captions)
          SubtitleCue(
            start: caption.offset.inMilliseconds,
            end: caption.end.inMilliseconds,
            text: caption.text,
          ),
      ];
      cues.sort((a, b) => a.start.compareTo(b.start));
      return cues;
    } finally {
      yt.close();
    }
  }
}
