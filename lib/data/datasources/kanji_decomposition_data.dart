  static List<String> findKanjiByComponents(List<String> selectedComponents) {
    if (selectedComponents.isEmpty) return [];
    final results = <String>[];
    for (final entry in _decompositions.entries) {
      final components = entry.value.components;
      bool allFound = true;
      for (final sc in selectedComponents) {
        if (!components.any((c) => c == sc)) {
          allFound = false;
          break;
        }
      }
      if (allFound) {
        results.add(entry.key);
      }
    }
    return results;
  }

  static List<String> findKanjiByAnyComponent(List<String> selectedComponents) {
    if (selectedComponents.isEmpty) return [];
    final results = <String>[];
    for (final entry in _decompositions.entries) {
      final components = entry.value.components;
      for (final sc in selectedComponents) {
        if (components.contains(sc)) {
          results.add(entry.key);
          break;
        }
      }
    }
    return results;
  }

