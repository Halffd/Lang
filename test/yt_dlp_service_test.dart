import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:lang/core/services/yt_dlp_service.dart';
import 'package:lang/core/services/youtube_resolver.dart';
import 'package:lang/core/services/youtube_service.dart';
import 'package:lang/utils/subtitle_parser.dart';

/// A minimal `yt-dlp -J` payload with the shapes the parser relies on:
/// muxed + video-only + audio-only formats, manual subtitles in several
/// format variants and automatic captions.
Map<String, dynamic> fixture() =>
    jsonDecode(r'''
{
  "id": "jNQXAC9IVRw",
  "title": "Me at the zoo",
  "uploader": "jawed",
  "formats": [
    {"format_id": "140", "ext": "m4a", "vcodec": "none", "acodec": "mp4a.40.2", "url": "https://audio/140"},
    {"format_id": "242", "ext": "webm", "vcodec": "vp9", "acodec": "none", "url": "https://video/242", "height": 240},
    {"format_id": "18", "ext": "mp4", "vcodec": "avc1.42001E", "acodec": "mp4a.40.2", "url": "https://muxed/18", "height": 360},
    {"format_id": "22", "ext": "mp4", "vcodec": "avc1.64001F", "acodec": "mp4a.40.2", "url": "https://muxed/22", "height": 720},
    {"format_id": "18-p60", "ext": "mp4", "vcodec": "avc1", "acodec": "mp4a", "url": "https://muxed/18b", "height": 360}
  ],
  "subtitles": {
    "ja": [
      {"ext": "srv1", "url": "https://tt/ja.srv1", "name": "Japanese"},
      {"ext": "vtt", "url": "https://tt/ja.vtt", "name": "Japanese"},
      {"ext": "json3", "url": "https://tt/ja.json3", "name": "Japanese"}
    ],
    "en": [
      {"ext": "srv3", "url": "https://tt/en.srv3", "name": "English"},
      {"ext": "ttml", "url": "https://tt/en.ttml", "name": "English"}
    ]
  },
  "automatic_captions": {
    "ja": [
      {"ext": "vtt", "url": "https://tt/ja-auto.vtt", "name": "Japanese"}
    ]
  }
}
''')
        as Map<String, dynamic>;

ProcessResult ok(String stdout) => ProcessResult(0, 0, stdout, '');
ProcessResult fail(String stderr) => ProcessResult(0, 1, '', stderr);

void main() {
  group('YtDlpService.videoInfoFromJson', () {
    test('keeps muxed formats only, labeled by height, sorted', () {
      final info = YtDlpService.videoInfoFromJson(fixture());
      expect(info, isNotNull);
      expect(info!.videoId, 'jNQXAC9IVRw');
      expect(info.title, 'Me at the zoo');
      expect(info.author, 'jawed');
      expect(info.qualities.map((q) => q.label), ['360p', '720p']);
      // 360p deduped to the first listed stream, best = last
      expect(info.qualities.first.url, 'https://muxed/18');
      expect(info.best.url, 'https://muxed/22');
    });

    test('returns null when no muxed stream exists', () {
      final json = fixture()
        ..['formats'] = [
          {
            'ext': 'm4a',
            'vcodec': 'none',
            'acodec': 'mp4a',
            'url': 'https://a',
          },
          {
            'ext': 'webm',
            'vcodec': 'vp9',
            'acodec': 'none',
            'url': 'https://v',
            'height': 720,
          },
        ];
      expect(YtDlpService.videoInfoFromJson(json), isNull);
    });

    test('returns null without an id', () {
      final json = fixture()..remove('id');
      expect(YtDlpService.videoInfoFromJson(json), isNull);
    });

    test('upstream falls back to channel when uploader is absent', () {
      final json = fixture()
        ..remove('uploader')
        ..['channel'] = 'jawed channel';
      expect(YtDlpService.videoInfoFromJson(json)!.author, 'jawed channel');
    });
  });

  group('YtDlpService.captionTracksFromJson', () {
    test('manual tracks first, one per language, parseable variant picked', () {
      final tracks = YtDlpService.captionTracksFromJson(
        fixture(),
        'jNQXAC9IVRw',
      );
      // en is manual but lists only XML variants (srv3/ttml), which no
      // local parser understands, so it is skipped entirely
      expect(tracks.map((t) => t.languageCode).toList(), ['ja', 'ja']);
      // ja manual: vtt picked over srv1/json3
      expect(tracks[0].url, 'https://tt/ja.vtt');
      expect(tracks[0].autoGenerated, isFalse);
      // ja auto comes after every manual track
      expect(tracks[1].url, 'https://tt/ja-auto.vtt');
      expect(tracks[1].autoGenerated, isTrue);
    });

    test('empty when nothing is available', () {
      final json = fixture()
        ..['subtitles'] = {}
        ..['automatic_captions'] = {};
      expect(YtDlpService.captionTracksFromJson(json, 'x'), isEmpty);
    });
  });

  group('YtDlpService availability probe', () {
    test('unavailable when the binary is missing', () async {
      final service = YtDlpService(
        runProcess: (_, _) async => throw ProcessException('yt-dlp', []),
      );
      expect(await service.isAvailable(), isFalse);
      expect(await service.resolve('https://youtu.be/x'), isNull);
    });

    test('unavailable when the binary exits non-zero', () async {
      final service = YtDlpService(runProcess: (_, _) async => fail('boom'));
      expect(await service.isAvailable(), isFalse);
    });

    test('resolve returns null on a failed extraction', () async {
      final service = YtDlpService(
        runProcess: (_, _) async => fail('bot check'),
      );
      // availability probe succeeds, extraction fails
      final service2 = YtDlpService(
        runProcess: (cmd, args) async =>
            args.contains('--version') ? ok('2026.08.19') : fail('bot check'),
      );
      expect(await service.isAvailable(), isFalse);
      expect(await service2.resolve('https://youtu.be/x'), isNull);
    });

    test('resolve parses a successful extraction', () async {
      final service = YtDlpService(
        runProcess: (cmd, args) async => args.contains('--version')
            ? ok('2026.08.19')
            : ok(jsonEncode(fixture())),
      );
      final info = await service.resolve('https://youtu.be/jNQXAC9IVRw');
      expect(info, isNotNull);
      expect(info!.qualities, hasLength(2));
    });
  });

  group('YouTubeResolver fallback', () {
    test('uses yt-dlp when it serves the request', () async {
      final explodeCalls = <String>[];
      final resolver = YouTubeResolver(
        ytDlp: YtDlpService(
          runProcess: (cmd, args) async =>
              args.contains('--version') ? ok('1') : ok(jsonEncode(fixture())),
        ),
        explode: _FakeBackend(onResolve: (url) => explodeCalls.add(url)),
      );
      final info = await resolver.resolve('https://youtu.be/jNQXAC9IVRw');
      expect(info, isNotNull);
      expect(explodeCalls, isEmpty);
    });

    test('falls back to explode when yt-dlp extraction fails', () async {
      final resolver = YouTubeResolver(
        ytDlp: YtDlpService(
          runProcess: (cmd, args) async =>
              args.contains('--version') ? ok('1') : fail('bot check'),
        ),
        explode: _FakeBackend(
          info: YouTubeVideoInfo(
            videoId: 'x',
            title: 'fallback',
            author: '',
            qualities: [
              const YouTubeStreamOption(url: 'https://f/360', label: '360p'),
            ],
          ),
        ),
      );
      final info = await resolver.resolve('https://youtu.be/x');
      expect(info, isNotNull);
      expect(info!.title, 'fallback');
    });

    test('falls back to explode when yt-dlp is not installed', () async {
      final resolver = YouTubeResolver(
        ytDlp: YtDlpService(
          runProcess: (_, _) async => throw ProcessException('yt-dlp', []),
        ),
        explode: _FakeBackend(
          info: YouTubeVideoInfo(
            videoId: 'x',
            title: 'explode',
            author: '',
            qualities: [
              const YouTubeStreamOption(url: 'https://f/360', label: '360p'),
            ],
          ),
        ),
      );
      final info = await resolver.resolve('https://youtu.be/x');
      expect(info!.title, 'explode');
    });

    test('caption tracks prefer yt-dlp when it lists any', () async {
      final resolver = YouTubeResolver(
        ytDlp: YtDlpService(
          runProcess: (cmd, args) async =>
              args.contains('--version') ? ok('1') : ok(jsonEncode(fixture())),
        ),
        explode: _FakeBackend(
          tracks: [
            const YouTubeCaptionTrack(
              videoId: 'x',
              languageCode: 'de',
              languageName: 'German',
              autoGenerated: false,
            ),
          ],
        ),
      );
      final tracks = await resolver.captionTracks('jNQXAC9IVRw');
      expect(tracks.first.languageCode, 'ja');
    });
  });
}

class _FakeBackend implements YouTubeBackend {
  _FakeBackend({this.info, this.tracks, this.onResolve});

  final YouTubeVideoInfo? info;
  final List<YouTubeCaptionTrack>? tracks;
  final void Function(String url)? onResolve;

  @override
  Future<YouTubeVideoInfo?> resolve(String url) async {
    onResolve?.call(url);
    return info;
  }

  @override
  Future<List<YouTubeCaptionTrack>> captionTracks(String videoId) async =>
      tracks ?? [];

  @override
  Future<List<SubtitleCue>> fetchCaptions(YouTubeCaptionTrack track) async =>
      [];
}
